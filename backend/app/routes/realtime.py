from datetime import datetime
from typing import Dict, List

from fastapi import APIRouter

from app.services import live_feed

router = APIRouter(prefix="/api/live", tags=["Live Signals"])


@router.get("/alerts")
def get_live_alerts() -> List[Dict]:
    """
    Latest items from WHO Disease Outbreak News (official) and news feeds
    (media reports, unverified), tagged with the Indian states and diseases
    they mention.
    """
    return live_feed.get_alerts()


@router.get("/geo-alerts")
def get_geo_alerts():
    """
    Live items aggregated by the Indian state they mention, for the map.
    A flagged state means it was named in a report, not that an outbreak is confirmed.
    """
    return live_feed.get_geo_alerts()


@router.get("/guidance")
def get_guidance(disease: str):
    """
    Public-health guidance for a disease, summarised from the cited source
    (WHO / CDC fact sheets) in app/resources/realtime.json. Not generated by
    a model and not specific to any location.
    """
    return live_feed.get_guidance(disease)
